// Extracts the numerical coefficient tables of the pinned IAU SOFA 2023-10-11 C routines
// (nut00a, epv00, dtdb) into UFUQ-owned TypeScript table modules. The source files live
// in the private, Git-ignored local reference library; every input file hash is checked
// against the pinned values below before anything is written. Numbers are copied as the
// exact decimal tokens of the C source, so JavaScript parses them to the same doubles.
//
// Usage: node scripts/codegen/extract-sofa-tables.mjs [sofaSrcDir]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const repositoryRoot = resolve(import.meta.dirname, '..', '..');
const defaultSourceDirectory = join(
  repositoryRoot,
  'local-reference/standards/iau-sofa/2023-10-11/source/sofa/20231011/c/src',
);
const sourceDirectory = resolve(process.argv[2] ?? defaultSourceDirectory);
const outputDirectory = join(repositoryRoot, 'packages/astronomy-core/src/astrometry/tables');

// SHA-256 of each pinned SOFA 2023-10-11 source file (sofa_c-20231011.zip,
// SHA-256 375729d8c0a254fd27c55484de5c8b83cccef351e1ef19d9cf7f26f5485e5538).
const PINNED_SOURCE_SHA256 = JSON.parse(
  readFileSync(join(import.meta.dirname, 'sofa-2023-10-11-source-hashes.json'), 'utf8'),
);

function readPinned(name) {
  const bytes = readFileSync(join(sourceDirectory, name));
  const digest = createHash('sha256').update(bytes).digest('hex');
  const expected = PINNED_SOURCE_SHA256[name];
  if (expected === undefined) throw new Error(`No pinned hash for ${name}.`);
  if (digest !== expected) {
    throw new Error(`SOFA source ${name} hash ${digest} differs from pinned ${expected}.`);
  }
  return { text: bytes.toString('latin1'), sha256: digest };
}

function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, ' ');
}

const NUMBER_TOKEN = /^[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?$/;

function numericTokens(block, label) {
  const tokens = block
    .replace(/[{}]/g, ' ')
    .split(/[\s,]+/)
    .filter((token) => token.length > 0);
  for (const token of tokens) {
    if (!NUMBER_TOKEN.test(token)) throw new Error(`Unexpected token ${token} in ${label}.`);
  }
  return tokens;
}

function arrayBlock(source, declarationPattern, label) {
  const match = declarationPattern.exec(source);
  if (!match) throw new Error(`Could not find ${label}.`);
  const start = match.index + match[0].length;
  const end = source.indexOf('};', start);
  if (end < 0) throw new Error(`Unterminated ${label}.`);
  return source.slice(start, end);
}

function rows(block, width, label) {
  const tokens = numericTokens(block, label);
  if (tokens.length % width !== 0) {
    throw new Error(`${label} has ${tokens.length} values, not a multiple of ${width}.`);
  }
  return tokens;
}

function formatTable(name, tokens, width, comment) {
  const lines = [];
  for (let index = 0; index < tokens.length; index += width) {
    lines.push(`  ${tokens.slice(index, index + width).join(', ')},`);
  }
  return `/** ${comment} Row width ${width}; ${tokens.length / width} rows. */\nexport const ${name}: readonly number[] = [\n${lines.join('\n')}\n];\n`;
}

const NOTICE = (
  files,
) => `// GENERATED by scripts/codegen/extract-sofa-tables.mjs. Do not edit by hand.
//
// UFUQ derived work notice (SOFA Software License, clause 3): this file contains
// numerical coefficients extracted by the UFUQ project from software provided by the IAU
// SOFA Board under licence (release 2023-10-11). It does not itself constitute software
// provided by and/or endorsed by SOFA. The coefficients are copied unchanged as decimal
// tokens; only their container layout differs (flat row-major arrays instead of C
// structs). See ../SOFA_DERIVED_NOTICE.md for the reproduced licence requirements.
//
// Source files and SHA-256:
${files.map(({ name, sha256 }) => `//   ${name} ${sha256}`).join('\n')}
`;

const nut00a = readPinned('nut00a.c');
const nutSource = stripComments(nut00a.text);
const lunisolar = rows(
  arrayBlock(nutSource, /\}\s*xls\[\]\s*=\s*\{/, 'nut00a xls'),
  11,
  'nut00a xls',
);
const planetary = rows(
  arrayBlock(nutSource, /\}\s*xpl\[\]\s*=\s*\{/, 'nut00a xpl'),
  17,
  'nut00a xpl',
);
if (lunisolar.length / 11 !== 678 || planetary.length / 17 !== 687) {
  throw new Error('IAU 2000A series size differs from the pinned 678 + 687 terms.');
}
writeFileSync(
  join(outputDirectory, 'nutation-iau2000a-series.ts'),
  `${NOTICE([{ name: 'nut00a.c', sha256: nut00a.sha256 }])}
${formatTable(
  'LUNISOLAR_NUTATION_TERMS',
  lunisolar,
  11,
  'IAU 2000A luni-solar terms: nl, nlp, nf, nd, nom, sp, spt, cp, ce, cet, se (0.1 microarcsec).',
)}
${formatTable(
  'PLANETARY_NUTATION_TERMS',
  planetary,
  17,
  'IAU 2000A planetary terms: nl, nf, nd, nom, nme, nve, nea, nma, nju, nsa, nur, nne, npa, sp, cp, se, ce (0.1 microarcsec).',
)}`,
);

const epv00 = readPinned('epv00.c');
const epvSource = stripComments(epv00.text);
const epvNames = [
  'e0x',
  'e0y',
  'e0z',
  'e1x',
  'e1y',
  'e1z',
  'e2x',
  'e2y',
  'e2z',
  's0x',
  's0y',
  's0z',
  's1x',
  's1y',
  's1z',
  's2x',
  's2y',
  's2z',
];
const epvTables = epvNames.map((name) => {
  const tokens = rows(
    arrayBlock(epvSource, new RegExp(`static const double ${name}\\[\\]\\s*=\\s*\\{`), name),
    3,
    `epv00 ${name}`,
  );
  return formatTable(
    `EPV_${name.toUpperCase()}`,
    tokens,
    3,
    `epv00 ${name} series: amplitude, phase, frequency.`,
  );
});
writeFileSync(
  join(outputDirectory, 'earth-ephemeris-vsop2000-series.ts'),
  `${NOTICE([{ name: 'epv00.c', sha256: epv00.sha256 }])}
${epvTables.join('\n')}`,
);

const dtdb = readPinned('dtdb.c');
const dtdbSource = stripComments(dtdb.text);
const fairhd = rows(
  arrayBlock(dtdbSource, /fairhd\[787\]\[3\]\s*=\s*\{/, 'dtdb fairhd'),
  3,
  'dtdb fairhd',
);
if (fairhd.length / 3 !== 787) throw new Error('dtdb series size differs from 787 terms.');
writeFileSync(
  join(outputDirectory, 'tdb-tt-fairhead-series.ts'),
  `${NOTICE([{ name: 'dtdb.c', sha256: dtdb.sha256 }])}
${formatTable('FAIRHEAD_TDB_TERMS', fairhd, 3, 'Fairhead & Bretagnon 1990 terms: amplitude, frequency, phase.')}`,
);

console.log(
  `Extracted ${lunisolar.length / 11}+${planetary.length / 17} nutation terms, ${epvNames.length} epv00 series, and ${fairhd.length / 3} TDB-TT terms.`,
);
